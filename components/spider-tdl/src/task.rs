//! Task execution traits and runtime handler.
//!
//! This module defines the [`Task`] trait (implemented by the `#[task]` proc-macro for each
//! user-defined task function), the [`TaskHandler`] trait (the type-erased interface used by the
//! registration macro's dispatch table), and [`TaskHandlerImpl`] (the bridge between them).

use std::marker::PhantomData;

use spider_core::job::submission::CompressedJobSubmission;
use spider_core::task::TaskContextRaw;
use spider_core::types::io::TaskInputsSerializer;
use spider_core::types::io::TaskOutputsSerializer;
use spider_utils::wire::WireError;
use spider_utils::wire::WireFrameBuilder;

use crate::error::TdlError;
use crate::task_context::TaskContext;

/// The result of executing a task through the [`TaskHandler`] interface.
///
/// Both variants carry a byte buffer:
///
/// * [`ExecutionResult::Ok`] holds a wire-format [`ExecutionSuccessOutcome`].
/// * [`ExecutionResult::Err`] holds a msgpack-encoded [`TdlError`].
pub type ExecutionResult = std::result::Result<Vec<u8>, Vec<u8>>;

/// Wire-format task outputs and child job submissions in submission order.
///
/// The serialized form consists of two consecutive wire frames. The first contains the task
/// outputs. The second contains a graph payload followed by an inputs payload for each child.
#[derive(Debug)]
pub struct ExecutionSuccessOutcome {
    pub outputs: Vec<u8>,
    pub children: Vec<CompressedJobSubmission>,
}

impl ExecutionSuccessOutcome {
    /// Decodes the outputs and child submissions frames.
    ///
    /// # Returns
    ///
    /// The task outputs and child submissions on success.
    ///
    /// # Errors
    ///
    /// Returns an error if:
    ///
    /// * [`TdlError::DeserializationError`] if either frame is malformed, a child payload is
    ///   missing its pair, or bytes follow the second frame.
    pub fn from_wire(bytes: Vec<u8>) -> Result<Self, TdlError> {
        let to_decode_error = |error: WireError| TdlError::DeserializationError(error.to_string());
        let (_, remaining) =
            WireFrameBuilder::unframe_payload_slices(&bytes).map_err(to_decode_error)?;
        let outputs_len = bytes.len() - remaining.len();
        let (child_payloads, remaining) =
            WireFrameBuilder::unframe_payload_slices(remaining).map_err(to_decode_error)?;
        if !remaining.is_empty() {
            return Err(to_decode_error(WireError::InvalidFormat(
                "bytes after child submissions frame",
            )));
        }
        let (children, unpaired) = child_payloads.as_chunks::<2>();
        if !unpaired.is_empty() {
            return Err(to_decode_error(WireError::InvalidFormat(
                "child submission is missing its inputs payload",
            )));
        }
        let outcome = Self {
            outputs: bytes[..outputs_len].to_vec(),
            children: children
                .iter()
                .map(|[graph, inputs]| CompressedJobSubmission {
                    compressed_serialized_task_graph: graph.to_vec(),
                    compressed_serialized_job_inputs: inputs.to_vec(),
                })
                .collect(),
        };
        drop(bytes);
        Ok(outcome)
    }

    /// Appends the child submissions frame to the outputs frame.
    ///
    /// # Returns
    ///
    /// The two consecutive frames on success.
    ///
    /// # Errors
    ///
    /// Returns an error if:
    ///
    /// * Forwards [`WireFrameBuilder::append_payload`]'s return values on failure.
    fn into_wire(self) -> Result<Vec<u8>, WireError> {
        let mut builder = WireFrameBuilder::with_prefix(self.outputs);
        for child in self.children {
            builder.append_payload(&child.compressed_serialized_task_graph)?;
            builder.append_payload(&child.compressed_serialized_job_inputs)?;
        }
        Ok(builder.release())
    }
}

/// Trait implemented by the `#[task]` proc-macro for each user-defined task function.
///
/// It is intended to be implemented by the proc-macro's generated code. Manually implementing this
/// trait must follow the contract outlined in the docstrings.
///
/// The proc-macro generates a marker struct, a params struct, and an impl of this trait that wires
/// deserialized parameters into the user's function body.
pub trait Task {
    /// The deserialized parameter struct (generated by the proc-macro, excludes [`TaskContext`]).
    type Params: for<'deserializer_lifetime> serde::Deserialize<'deserializer_lifetime>;

    /// The return type of the task (must be a tuple, even for single values).
    ///
    /// NOTE: Unfortunately, the tuple trait is a nightly-only feature. Otherwise, we should enforce
    /// the type to implement [`std::marker::Tuple`]. For now, the type error can only be reported
    /// at runtime.
    type Return: serde::Serialize;

    /// The name of the task, used as the lookup key in the registration table.
    const NAME: &'static str;

    /// Executes the task with the given context and deserialized parameters.
    ///
    /// # Parameters
    ///
    /// * `ctx` - The runtime metadata passed to every task.
    /// * `params` - The deserialized task parameter struct.
    ///
    /// # Returns
    ///
    /// The task's return tuple on success.
    ///
    /// # Errors
    ///
    /// Returns a [`TdlError`] on failure.
    fn execute(ctx: TaskContext, params: Self::Params) -> Result<Self::Return, TdlError>;

    /// Serializes the return tuple into wire-format bytes.
    ///
    /// # Parameters
    ///
    /// * `result` - The task's return tuple.
    ///
    /// # Returns
    ///
    /// The wire-format byte stream on success.
    ///
    /// # Errors
    ///
    /// Returns an error if:
    ///
    /// * [`TdlError::SerializationError`] if it fails to serialize the return tuple.
    fn serialize_return(result: &Self::Return) -> Result<Vec<u8>, TdlError> {
        TaskOutputsSerializer::from_tuple(result)
            .map_err(|e| TdlError::SerializationError(e.to_string()))
    }
}

/// Type-erased task execution interface.
///
/// Used by the registration macro's dispatch table to invoke tasks by name without knowing the
/// concrete [`Task`] type. Implementations must be thread-safe since the dispatch table is a
/// `static` object shared across threads.
pub trait TaskHandler: Send + Sync {
    /// Executes the task from raw serialized inputs.
    ///
    /// # Parameters
    ///
    /// * `raw_ctx` - Msgpack-encoded task metadata.
    /// * `raw_args` - Wire-format-encoded task inputs.
    ///
    /// # Returns
    ///
    /// The wire-format [`ExecutionSuccessOutcome`] on success.
    ///
    /// # Errors
    ///
    /// A serialized [`TdlError`] if decoding inputs or context, executing the task, or serializing
    /// its result fails.
    fn execute_raw(&self, raw_ctx: &[u8], raw_args: &[u8]) -> ExecutionResult;

    /// # Returns
    ///
    /// The task's registered name ([`Task::NAME`]).
    fn name(&self) -> &'static str;
}

/// Bridges a concrete [`Task`] implementation to the type-erased [`TaskHandler`] interface.
///
/// Decodes task metadata and parameters, delegates to [`Task::execute`], and serializes the
/// result.
///
/// # Type Parameters
///
/// * `TaskType` - The concrete [`Task`] implementation.
pub struct TaskHandlerImpl<TaskType: Task> {
    _marker: PhantomData<TaskType>,
}

impl<TaskType: Task> TaskHandlerImpl<TaskType> {
    /// Factory function.
    ///
    /// # Returns
    ///
    /// A newly created handler for the given task type.
    #[must_use]
    pub const fn new() -> Self {
        Self {
            _marker: PhantomData,
        }
    }
}

impl<TaskType: Task + Send + Sync> TaskHandler for TaskHandlerImpl<TaskType> {
    fn execute_raw(&self, raw_ctx: &[u8], raw_args: &[u8]) -> ExecutionResult {
        let raw: TaskContextRaw = rmp_serde::from_slice(raw_ctx).map_err(|e| {
            serialize_error(&TdlError::DeserializationError(format!(
                "failed to deserialize task metadata: {e}"
            )))
        })?;
        let params: TaskType::Params = TaskInputsSerializer::deserialize(raw_args)
            .map_err(|e| serialize_error(&TdlError::DeserializationError(e.to_string())))?;
        let (ctx, child_job_submission_receiver) = TaskContext::from_raw(raw);
        let result = TaskType::execute(ctx, params);
        let children = child_job_submission_receiver.take();
        let outputs = result
            .and_then(|result_tuple| TaskType::serialize_return(&result_tuple))
            .map_err(|e| serialize_error(&e))?;
        let outcome = ExecutionSuccessOutcome { outputs, children };
        outcome
            .into_wire()
            .map_err(|e| serialize_error(&TdlError::SerializationError(e.to_string())))
    }

    fn name(&self) -> &'static str {
        TaskType::NAME
    }
}

impl<TaskType: Task> Default for TaskHandlerImpl<TaskType> {
    fn default() -> Self {
        Self::new()
    }
}

/// # Returns
///
/// The given `err` serialized as a msgpack byte stream.
///
/// # Panics
///
/// Panics if the serialization fails ([`rmp_serde::to_vec`]). The messagepack serialization should
/// always success.
fn serialize_error(err: &TdlError) -> Vec<u8> {
    rmp_serde::to_vec(err).expect("failed to serialize `TdlError` as msgpack")
}

#[cfg(test)]
mod tests {
    use std::cell::RefCell;

    use serde::Deserialize;
    use serde::Serialize;
    use spider_core::task::TaskGraph;
    use spider_core::types::id::JobId;
    use spider_core::types::id::ResourceGroupId;
    use spider_core::types::id::TaskId;
    use spider_core::types::io::TaskGraphInputBuilder;
    use spider_core::types::io::TaskInput;
    use spider_core::types::io::TaskInputsSerializer;
    use spider_core::types::io::TaskOutputsSerializer;

    use super::*;
    use crate::error::TdlError;
    use crate::r#std::int32;
    use crate::task_context::TaskContext;

    const INTENTIONAL_FAILURE: &str = "intentional failure";

    thread_local! {
        static RETAINED_CONTEXT: RefCell<Option<TaskContext>> = const { RefCell::new(None) };
    }

    #[derive(Deserialize)]
    struct AddParams {
        a: int32,
        b: int32,
    }

    struct Add;

    impl Add {
        fn make_inputs(a: int32, b: int32) -> anyhow::Result<Vec<u8>> {
            let mut inputs = TaskInputsSerializer::new();
            inputs.append(TaskInput::ValuePayload(rmp_serde::to_vec(&a)?))?;
            inputs.append(TaskInput::ValuePayload(rmp_serde::to_vec(&b)?))?;
            Ok(inputs.release())
        }
    }

    impl Task for Add {
        type Params = AddParams;
        type Return = (int32,);

        const NAME: &'static str = "test::add";

        fn execute(_ctx: TaskContext, params: Self::Params) -> Result<Self::Return, TdlError> {
            Ok((params.a + params.b,))
        }
    }

    #[derive(Deserialize)]
    struct EmptyParams {}

    struct AlwaysFail;

    impl Task for AlwaysFail {
        type Params = EmptyParams;
        type Return = (int32,);

        const NAME: &'static str = "test::fail";

        fn execute(_ctx: TaskContext, _params: Self::Params) -> Result<Self::Return, TdlError> {
            Err(TdlError::ExecutionError(INTENTIONAL_FAILURE.to_owned()))
        }
    }

    #[derive(Serialize)]
    struct IllegalReturn {
        value: int32,
    }

    /// Illegal [`Task`] impl: `Return` is a struct rather than a tuple. Because the tuple
    /// constraint is runtime-checked (see the [`Task::Return`] docstring), such an impl compiles
    /// but fails inside [`TaskHandler::execute_raw`] at the serialization step.
    struct Illegal;

    impl Task for Illegal {
        type Params = EmptyParams;
        type Return = IllegalReturn;

        const NAME: &'static str = "test::illegal";

        fn execute(_ctx: TaskContext, _params: Self::Params) -> Result<Self::Return, TdlError> {
            Ok(IllegalReturn { value: 0 })
        }
    }

    #[derive(Serialize, Deserialize)]
    enum SubmitMode {
        Succeed,
        FailExecution,
        FailSerialization,
    }

    #[derive(Deserialize)]
    struct SubmitParams {
        mode: SubmitMode,
    }

    struct SubmitChild;

    impl Task for SubmitChild {
        type Params = SubmitParams;
        type Return = (SubmitMode,);

        const NAME: &'static str = "test::submit_child";

        fn execute(ctx: TaskContext, params: Self::Params) -> Result<Self::Return, TdlError> {
            ctx.create_child_job_submission(
                &TaskGraph::default(),
                &TaskGraphInputBuilder::new().build(),
            )?;
            RETAINED_CONTEXT.with(|retained| *retained.borrow_mut() = Some(ctx));
            match params.mode {
                SubmitMode::Succeed | SubmitMode::FailSerialization => Ok((params.mode,)),
                SubmitMode::FailExecution => {
                    Err(TdlError::ExecutionError(INTENTIONAL_FAILURE.to_owned()))
                }
            }
        }

        fn serialize_return(result: &Self::Return) -> Result<Vec<u8>, TdlError> {
            RETAINED_CONTEXT.with(|retained| {
                let retained = retained.borrow();
                assert_child_submissions_closed(
                    retained.as_ref().expect("task must retain its context"),
                );
            });
            match result.0 {
                SubmitMode::Succeed | SubmitMode::FailExecution => {
                    TaskOutputsSerializer::from_tuple(result)
                        .map_err(|e| TdlError::SerializationError(e.to_string()))
                }
                SubmitMode::FailSerialization => {
                    Err(TdlError::SerializationError(INTENTIONAL_FAILURE.to_owned()))
                }
            }
        }
    }

    fn assert_child_submissions_closed(ctx: &TaskContext) {
        assert!(matches!(
            ctx.create_child_job_submission(
                &TaskGraph::default(),
                &TaskGraphInputBuilder::new().build(),
            ),
            Err(TdlError::InvalidTaskContext(_))
        ));
    }

    fn make_encoded_ctx() -> Vec<u8> {
        let ctx = TaskContextRaw::new(
            JobId::random(),
            TaskId::Index(0),
            1,
            ResourceGroupId::random(),
            None,
        )
        .expect("failed to build task metadata");
        rmp_serde::to_vec(&ctx).expect("failed to serialize task metadata")
    }

    /// Asserts the given result contains a deserialization error
    /// (`[TdlError::DeserializationError]`).
    fn assert_deserialization_failure(result: ExecutionResult) {
        match result {
            Ok(_) => panic!("expected error"),
            Err(bytes) => {
                let err: TdlError =
                    rmp_serde::from_slice(&bytes).expect("failed to deserialize error");
                assert!(matches!(err, TdlError::DeserializationError(_)));
            }
        }
    }

    #[test]
    fn handler_success() -> anyhow::Result<()> {
        const A: int32 = 10;
        const B: int32 = 32;

        let handler = TaskHandlerImpl::<Add>::new();
        assert_eq!(handler.name(), "test::add");

        let raw_ctx = make_encoded_ctx();
        let raw_args = Add::make_inputs(A, B)?;

        let result = handler.execute_raw(&raw_ctx, &raw_args);
        match result {
            Ok(bytes) => {
                let mut expected = TaskOutputsSerializer::from_tuple(&(A + B,))?;
                expected.extend_from_slice(&0_u32.to_le_bytes());
                assert_eq!(bytes, expected);

                let ExecutionSuccessOutcome {
                    outputs: serialized_outputs,
                    children,
                } = ExecutionSuccessOutcome::from_wire(bytes)?;
                assert_eq!(children, Vec::new());
                let outputs = TaskOutputsSerializer::deserialize(&serialized_outputs)?;
                assert_eq!(outputs.len(), 1);
                let sum: int32 = rmp_serde::from_slice(&outputs[0])?;
                assert_eq!(sum, A + B);
            }
            Err(bytes) => {
                let err: TdlError = rmp_serde::from_slice(&bytes)?;
                panic!("unexpected error: {err}");
            }
        }
        Ok(())
    }

    #[test]
    fn success_outcome_rejects_malformed_child_frame() -> anyhow::Result<()> {
        let outputs = TaskOutputsSerializer::new().release();
        let mut trailing_bytes = WireFrameBuilder::with_prefix(outputs.clone()).release();
        trailing_bytes.push(0);
        let mut builder = WireFrameBuilder::with_prefix(outputs.clone());
        builder.append_payload(b"graph")?;

        for (bytes, diagnostic) in [
            (
                outputs,
                "invalid wire format: buffer too small for the payload count header",
            ),
            (
                trailing_bytes,
                "invalid wire format: bytes after child submissions frame",
            ),
            (
                builder.release(),
                "invalid wire format: child submission is missing its inputs payload",
            ),
        ] {
            let error = ExecutionSuccessOutcome::from_wire(bytes)
                .expect_err("malformed child frame must fail");
            assert_eq!(error, TdlError::DeserializationError(diagnostic.to_owned()));
        }
        Ok(())
    }

    #[test]
    fn handler_task_error() -> anyhow::Result<()> {
        let handler = TaskHandlerImpl::<AlwaysFail>::new();

        let raw_ctx = make_encoded_ctx();
        let raw_args = TaskInputsSerializer::new().release();

        let result = handler.execute_raw(&raw_ctx, &raw_args);
        match result {
            Ok(_) => panic!("expected error"),
            Err(bytes) => {
                let err: TdlError = rmp_serde::from_slice(&bytes)?;
                assert!(
                    matches!(err, TdlError::ExecutionError(ref msg) if msg == INTENTIONAL_FAILURE)
                );
            }
        }
        Ok(())
    }

    #[test]
    fn handler_bad_ctx() -> anyhow::Result<()> {
        let handler = TaskHandlerImpl::<Add>::new();
        let raw_args = Add::make_inputs(1, 2)?;

        // 0xC1 is a reserved/invalid msgpack byte.
        let result = handler.execute_raw(&[0xc1], &raw_args);
        assert_deserialization_failure(result);
        Ok(())
    }

    #[test]
    fn handler_bad_inputs() {
        let handler = TaskHandlerImpl::<Add>::new();
        let raw_ctx = make_encoded_ctx();

        // Pass truncated wire data.
        let result = handler.execute_raw(&raw_ctx, &[0x01]);
        assert_deserialization_failure(result);
    }

    #[test]
    fn handler_illegal_non_tuple_return() -> anyhow::Result<()> {
        let handler = TaskHandlerImpl::<Illegal>::new();
        let raw_ctx = make_encoded_ctx();
        let raw_args = TaskInputsSerializer::new().release();

        let result = handler.execute_raw(&raw_ctx, &raw_args);
        match result {
            Ok(_) => panic!("expected serialization error for non-tuple return"),
            Err(bytes) => {
                let err: TdlError = rmp_serde::from_slice(&bytes)?;
                assert!(matches!(err, TdlError::SerializationError(_)));
            }
        }
        Ok(())
    }

    #[test]
    fn handler_closes_submissions_on_success_and_failure() -> anyhow::Result<()> {
        let handler = TaskHandlerImpl::<SubmitChild>::new();
        let raw_ctx = make_encoded_ctx();
        for mode in [
            SubmitMode::Succeed,
            SubmitMode::FailExecution,
            SubmitMode::FailSerialization,
        ] {
            let mut inputs = TaskInputsSerializer::new();
            inputs.append(TaskInput::ValuePayload(rmp_serde::to_vec(&mode)?))?;
            let result = handler.execute_raw(&raw_ctx, &inputs.release());
            match mode {
                SubmitMode::Succeed => {
                    let bytes = result.expect("child-producing task must succeed");
                    let ExecutionSuccessOutcome {
                        outputs: serialized_outputs,
                        children,
                    } = ExecutionSuccessOutcome::from_wire(bytes)?;
                    assert_eq!(children.len(), 1);
                    assert_eq!(
                        TaskOutputsSerializer::deserialize(&serialized_outputs)?,
                        vec![rmp_serde::to_vec(&mode)?]
                    );
                }
                SubmitMode::FailExecution | SubmitMode::FailSerialization => {
                    let bytes = result.expect_err("task must fail");
                    let error: TdlError = rmp_serde::from_slice(&bytes)?;
                    let reason = match (mode, error) {
                        (SubmitMode::FailExecution, TdlError::ExecutionError(reason))
                        | (SubmitMode::FailSerialization, TdlError::SerializationError(reason)) => {
                            reason
                        }
                        (_, error) => panic!("unexpected task error: {error:?}"),
                    };
                    assert_eq!(reason, INTENTIONAL_FAILURE);
                }
            }
            let retained = RETAINED_CONTEXT
                .with(|ctx| ctx.borrow_mut().take())
                .expect("task must retain its context");
            assert_child_submissions_closed(&retained);
        }
        Ok(())
    }
}
